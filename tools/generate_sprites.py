from pathlib import Path
from PIL import Image

BASE_DIR = Path(__file__).resolve().parents[1]
OUTPUT_DIR = BASE_DIR / "assets" / "characters"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def hex_to_rgba(hex_color):
    hex_color = hex_color.lstrip('#')
    r = int(hex_color[0:2], 16)
    g = int(hex_color[2:4], 16)
    b = int(hex_color[4:6], 16)
    return r, g, b, 255


def paint_sprite(name, palette, pixels):
    height = len(pixels)
    width = len(pixels[0]) if height else 0
    assert width == 16 and height == 16, f"Sprite {name} must be 16x16, got {width}x{height}"

    image = Image.new('RGBA', (width, height), (0, 0, 0, 0))
    for y, row in enumerate(pixels):
        assert len(row) == width, f"Row {y} in sprite {name} has invalid width {len(row)}"
        for x, idx in enumerate(row):
            color_hex = palette.get(idx)
            if not color_hex:
                continue
            image.putpixel((x, y), hex_to_rgba(color_hex))

    out_path = OUTPUT_DIR / f"{name}.png"
    image.save(out_path)
    print(f"Saved {out_path.relative_to(BASE_DIR)}")


